public class SimpleMath {
    public static void main(String[] args) {
        int x = 10;
        int y = 25;
        int sum = x + y;

        if (sum > 30) {
            System.out.println("The sum is: " + sum);
        } else {
            System.out.println("Sum is 30 or less.");
        }
    }
}
